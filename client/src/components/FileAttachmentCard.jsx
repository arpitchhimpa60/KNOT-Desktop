export default function FileAttachmentCard({
  attachment,
  messageId,
  isDownloading,
  onDownload,
}) {
  if (!attachment || !attachment.originalName) return null;

  const originalName = attachment.originalName;
  const category = getFileCategory(originalName, attachment.mimeType);
  const badgeText = getFileBadgeText(originalName);
  const sizeFormatted = formatFileSize(attachment.fileSize);

  return (
    <div className="message-attachment-card">
      <div
        className={`file-badge file-badge-${category}`}
        title={`${badgeText} file`}
        aria-label={`${badgeText} file`}
      >
        <span className="file-badge-icon">
          <FileCategoryIcon category={category} />
        </span>
        <span className="file-badge-text">{badgeText}</span>
      </div>

      <div className="file-card-details">
        <span
          className="file-card-name"
          title={originalName}
        >
          {originalName}
        </span>
        <span className="file-card-size">
          {sizeFormatted}
        </span>
      </div>

      <button
        type="button"
        className="file-card-download-btn"
        onClick={(e) => {
          e.stopPropagation();
          if (onDownload) {
            onDownload(messageId, originalName);
          }
        }}
        disabled={isDownloading}
        title={isDownloading ? "Downloading..." : `Download ${originalName}`}
        aria-label={`Download ${originalName}`}
      >
        {isDownloading ? (
          <span className="file-download-spinner" aria-hidden="true" />
        ) : (
          <svg
            className="file-download-icon"
            width="15"
            height="15"
            viewBox="0 0 24 24"
            fill="none"
            stroke="currentColor"
            strokeWidth="2.2"
            strokeLinecap="round"
            strokeLinejoin="round"
            aria-hidden="true"
          >
            <path d="M21 15v4a2 2 0 0 1-2 2H5a2 2 0 0 1-2-2v-4" />
            <polyline points="7 10 12 15 17 10" />
            <line x1="12" y1="15" x2="12" y2="3" />
          </svg>
        )}
      </button>
    </div>
  );
}
